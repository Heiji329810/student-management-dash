function translateValue(value: string, language: 'en' | 'zh'): string {
  if (language === 'en') return value;
  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  const trimmed = value.trim();
  if (!trimmed) return value;
  return `${leading}${translateDynamicText(trimmed)}${trailing}`;
}

function translateTextNode(node: Text, language: 'en' | 'zh') {
  if (node.parentElement?.closest('[data-i18n-managed]')) return;
  const current = node.nodeValue ?? '';
  let original = originals.get(node);
  if (original === undefined) {
    original = current;
    originals.set(node, original);
  } else {
    const translated = translateValue(original, 'zh');
    if (current !== original && current !== translated) {
      original = current;
      originals.set(node, original);
    }
  }
  const next = translateValue(original, language);
  if (current !== next) node.nodeValue = next;
}

function translateElementAttributes(element: Element, language: 'en' | 'zh') {
  if (element.closest('[data-i18n-managed]')) return;
  const attributes = ['placeholder', 'title', 'aria-label'];
  let values = translatedAttributes.get(element);
  if (!values) {
    values = new Map();
    translatedAttributes.set(element, values);
  }
  for (const attribute of attributes) {
    const current = element.getAttribute(attribute);
    if (!current) continue;
    let original = values.get(attribute);
    if (original === undefined) {
      original = current;
      values.set(attribute, original);
    } else {
      const translated = translateValue(original, 'zh');
      if (current !== original && current !== translated) {
        original = current;
        values.set(attribute, original);
      }
    }
    const next = translateValue(original, language);
    if (current !== next) element.setAttribute(attribute, next);
  }
}

function translateTree(root: Node, language: 'en' | 'zh') {
  if (root instanceof Text) {
    translateTextNode(root, language);
    return;
  }
  if (!(root instanceof Element) && root !== document.body) return;
  if (root instanceof Element) {
    if (['SCRIPT', 'STYLE'].includes(root.tagName)) return;
    translateElementAttributes(root, language);
  }
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    if (node instanceof Text) translateTextNode(node, language);
    if (node instanceof Element) translateElementAttributes(node, language);
    node = walker.nextNode();
  }
}

export function applyPageLanguage(language: 'en' | 'zh'): () => void {
  translateTree(document.body, language);
  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === 'characterData') {
        translateTree(mutation.target, language);
      } else {
        mutation.addedNodes.forEach((node) => translateTree(node, language));
        if (mutation.target instanceof Element) {
          translateElementAttributes(mutation.target, language);
        }
      }
    }
  });
  observer.observe(document.body, {
    childList: true,
    characterData: true,
    subtree: true,
    attributes: true,
    attributeFilter: ['placeholder', 'title', 'aria-label'],
  });
  return () => observer.disconnect();
}
